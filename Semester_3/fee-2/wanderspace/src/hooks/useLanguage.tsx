interface LanguageContextValue {
    language: Language;
    setLanguage: (language: Language) => void;
    t: (key: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

function readLanguage(): Language {
    const value = document.cookie
        .split("; ")
        .find((entry) => entry.startsWith(`${LANGUAGE_COOKIE}=`))
        ?.split("=")[1];
    return value && value in translations ? (value as Language) : "en";
}

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({
    children,
}) => {
    const [language, setLanguageState] = useState<Language>(readLanguage);

    const setLanguage = (nextLanguage: Language) => {
        setLanguageState(nextLanguage);
        document.cookie = `${LANGUAGE_COOKIE}=${nextLanguage}; Max-Age=${COOKIE_MAX_AGE}; Path=/; SameSite=Lax`;
    };

    useEffect(() => {
        document.documentElement.lang = language;
    }, [language]);

    const t = (key: string) =>
        translations[language][key] ||
        additionalTranslations[language][key] ||
        translations.en[key] ||
        key;

    return (
        <LanguageContext.Provider value={{ language, setLanguage, t }}>
            {children}
        </LanguageContext.Provider>
    );
};

export function useLanguage(): LanguageContextValue {
    const context = useContext(LanguageContext);
    if (!context) {
        throw new Error("useLanguage must be used within LanguageProvider");
    }
    return context;
}
